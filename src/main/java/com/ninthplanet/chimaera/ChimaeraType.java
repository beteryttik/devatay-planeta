package com.ninthplanet.chimaera;

/** Типы химер: био-узел и паразитированная техника. */
public enum ChimaeraType {
    BIO_BULB,      // как на арте: ядро + щупальца
    HELICOPTER,    // химера-вертолёт: парит, стреляет щупальцами сверху
    CAR,           // химера-машина: быстрый таран
    TANK           // химера-танк: медленный, толстая броня, ломает стены
}
